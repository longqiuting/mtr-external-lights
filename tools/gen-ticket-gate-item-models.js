#!/usr/bin/env node
// 从 Blockbench 原始素材生成闸机的「物品模型」（只有物品栏 / 手持用得上它）。
//
// 世界里闸机已经改走方块实体渲染器（直接读 rawmodels/*.json，任意角度与三轴旋转都能画）。
// 但物品模型必须是原版 block model，而原版一个元素只能**单轴**旋转，所以这里做两件事：
//   1. uv 原样保留（0..16 语义 = 整张贴图，和 rawmodels 里一致；旧版按 /4 处理是错的）；
//   2. 三轴旋转的元素取「角度绝对值最大的那个轴」，其余丢掉 —— 图标只有 16px，
//      一颗 45° 的螺栓看不出来，但整机轮廓是对的。
//
// 用法：node tools/gen-ticket-gate-item-models.js
// 输入：v1.20.1/src/main/resources/assets/mtrlte/rawmodels/<name>_closed.json
// 输出：v1.20.1/src/main/resources/assets/mtrlte/models/block/<name>_item.json
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', 'v1.20.1', 'src', 'main', 'resources', 'assets', 'mtrlte');
const RAW = path.join(ROOT, 'rawmodels');
const OUT = path.join(ROOT, 'models', 'block');

/** 0..16 保留 5 位小数，避免 12.000000000000002 这种噪声。 */
const num = (v) => Math.round(v * 1e5) / 1e5;

/** 原版模型 JSON 的角度**必须是 22.5 的整数倍**（1.20.1 的 ModelElement 反序列化里就写死了
 *  22.5f / 45.0f 两个常量，别的角度直接报 "Expected angle to be a multiple of 22.5"）。
 *  所以物品模型把角度吸附到最近的 22.5° —— 图标 16px，看不出差别。 */
const SNAP = 22.5;

function snapAngle(angle) {
  return Math.round(angle / SNAP) * SNAP;
}

/** 三轴旋转 → 单轴（取 |angle| 最大的那个轴），角度再吸到 22.5 的整数倍。 */
function singleAxis(rotation) {
  if (!rotation) {
    return null;
  }
  if (rotation.axis) {
    const angle = snapAngle(rotation.angle || 0);
    return angle === 0 ? null : { axis: rotation.axis, angle, origin: rotation.origin.map(num) };
  }
  const axes = ['x', 'y', 'z'];
  let best = null;
  for (const axis of axes) {
    const angle = Math.abs(rotation[axis] || 0);
    if (angle > 0 && (best === null || angle > best.angle)) {
      best = { axis, angle };
    }
  }
  if (!best) {
    return null;
  }
  const snapped = snapAngle(rotation[best.axis]);
  return snapped === 0 ? null : { axis: best.axis, angle: snapped, origin: rotation.origin.map(num) };
}

function convert(rawName, itemName, textureName) {
  const src = JSON.parse(fs.readFileSync(path.join(RAW, rawName + '_closed.json'), 'utf8'));
  const elements = src.elements.map((element) => {
    const elementOut = {
      from: element.from.map(num),
      to: element.to.map(num),
    };
    const rotation = singleAxis(element.rotation);
    if (rotation) {
      elementOut.rotation = { origin: rotation.origin, axis: rotation.axis, angle: rotation.angle, rescale: false };
    }
    if (element.shade === false) {
      elementOut.shade = false;
    }
    elementOut.faces = {};
    for (const [dir, face] of Object.entries(element.faces)) {
      const faceOut = {};
      if (face.uv) {
        faceOut.uv = face.uv.map(num);
      }
      faceOut.texture = '#tex';
      elementOut.faces[dir] = faceOut;
    }
    return elementOut;
  });

  const model = {
    credit: 'Generated by tools/gen-ticket-gate-item-models.js from rawmodels/' + rawName + '_closed.json',
    parent: 'block/block',
    textures: {
      particle: 'mtrlte:block/' + textureName,
      tex: 'mtrlte:block/' + textureName,
    },
    elements,
  };

  const target = path.join(OUT, itemName + '_item.json');
  fs.writeFileSync(target, JSON.stringify(model, null, 2) + '\n');
  console.log(
    '%s: %d elements -> %s',
    itemName,
    elements.length,
    path.relative(process.cwd(), target)
  );
}

convert('ticket_barrier', 'ticket_gate_xiamen', 'ticket_barrier');
convert('brt_barrier', 'ticket_gate_brt', 'brt_barrier');
